#!/usr/bin/env bash
# 무릎 판정의 자기검증 (TS-9).
#
# **이 판정이 착수 문턱의 근거가 된다.** 여기가 조용히 틀리면 그 문턱이 다시
# 근거 없는 수가 되고, 이번에는 실측이라는 이름표까지 붙는다.
set -uo pipefail
cd "$(git rev-parse --show-toplevel)" || exit 1

. test/load/selftest-lib.sh || exit 2
SELFTEST_JUDGE=$PWD/test/load/evaluate-knee.sh

work=$(mktemp -d) || exit 1
trap 'rm -rf "$work"' EXIT

# `<듀티%> <등록/초> <p99ms> <CPU%>` 네 칸씩.
rows() {
    local path=$work/$1
    shift
    printf '%s\n' "$@" > "$path"
    printf '%s' "$path"
}

echo "무릎 판정 자기검증"

# 지연이 기준선의 두 배를 넘는 첫 줄의 CPU 가 답이다.
run_case "꺾인 지점의 CPU 를 낸다" 0 "CPU 55.0% 다" \
    -- "$(rows knee.txt "1 1000 1.0 12.0" "2 2000 1.5 30.0" "4 4000 2.1 55.0" "8 5000 9.0 80.0")"

# **경계를 두 사례로 못 박는다.** 하나만 두면 부등호를 뒤집어도 초록이다.
run_case "정확히 두 배는 아직 아니다" 0 "CPU 80.0% 다" \
    -- "$(rows edge.txt "1 1000 1.0 12.0" "2 2000 2.0 30.0" "4 4000 2.0 55.0" "8 5000 2.1 80.0")"

# **끝까지 안 꺾이면 근거를 못 만든 것이다.** 통과로 끝내면 게이트가 초록으로
# 읽고 문턱은 근거 없는 채로 남는다. 그때 CPU 도 같이 내는지 본다 — 안 내면
# 얼마나 더 올려야 하는지를 다음 사람이 모른다.
run_case "안 꺾이면 판정 불가" 1 "무릎을 못 봤다" \
    -- "$(rows flat.txt "1 1000 1.0 12.0" "2 2000 1.2 30.0" "4 4000 1.4 55.0" "8 5000 1.6 80.0")"
run_case "안 꺾였을 때 최고 CPU 를 낸다" 1 "그때 CPU 80.0%" \
    -- "$(rows flat.txt "1 1000 1.0 12.0" "2 2000 1.2 30.0" "4 4000 1.4 55.0" "8 5000 1.6 80.0")"

# **표가 부하순이어야 한다.** 첫 줄을 기준선으로 쓰고 첫 초과에서 멈추는 규칙이
# 그 전제 위에 있다. 역순이면 가장 느린 줄이 기준선이 되어 무릎 셋을 놓친다.
run_case "부하순이 아니면 막는다" 1 "부하순이 아니다" \
    -- "$(rows rev.txt "128 5000 9.0 80.0" "64 4000 2.1 55.0" "2 2000 1.5 30.0" "1 1000 1.0 12.0")"

# **꺾인 지점의 등록/초도 낸다.** 안 물면 그 자리에 지연을 찍어도 초록이다.
run_case "꺾인 지점의 등록/초를 낸다" 0 "등록/초 *4000" \
    -- "$(rows knee.txt "1 1000 1.0 12.0" "2 2000 1.5 30.0" "4 4000 2.1 55.0" "8 5000 9.0 80.0")"

# **배수가 실제로 쓰이는지 본다.** 안 쓰면 어떤 값을 줘도 같은 답이 나온다.
KNEE_FACTOR=4 run_case "배수를 올리면 무릎도 뒤로 간다" 0 "CPU 80.0% 다" \
    -- "$(rows knee.txt "1 1000 1.0 12.0" "2 2000 1.5 30.0" "4 4000 2.1 55.0" "8 5000 9.0 80.0")"

# 기준선이 0 이면 곱해도 0 이라 첫 줄부터 꺾인 것으로 나온다 — 못 잰 것이다.
run_case "기준선이 0 이면 판정 불가" 1 "못 잰 것이다" \
    -- "$(rows zero.txt "1 1000 0 12.0" "2 2000 1.5 30.0" "4 4000 2.1 55.0" "8 5000 9.0 80.0")"

# 표본이 적으면 무릎을 못 본다. 두 점으로 꺾임을 말할 수 없다.
# **경계를 두 사례로 못 박는다.** 하한만 한쪽에서 보면 넷을 셋으로 낮춰도 초록이다.
run_case "표본이 적으면 판정 불가" 1 "무릎을 못 본다" \
    -- "$(rows few.txt "1 1000 1.0 12.0" "2 2000 1.2 30.0" "4 4000 9.0 55.0")"
run_case "하한을 채우면 판정한다" 0 "CPU 55.0% 다" \
    -- "$(rows just.txt "1 1000 1.0 12.0" "2 2000 1.2 30.0" "4 4000 9.0 55.0" "8 5000 9.5 80.0")"

# 계기가 흔들린 회차. 숫자가 아니면 awk 가 0 으로 읽어 조용히 지나간다.
run_case "숫자가 아니면 막는다" 1 "숫자가 아닌 칸" \
    -- "$(rows bad.txt "1 1000 1.0 12.0" "2 oops 1.5 30.0" "4 4000 2.1 55.0" "8 5000 9.0 80.0")"

# 칸 수가 다르면 자리를 잘못 읽는다. 그러면 CPU 자리에서 지연을 읽는다.
run_case "칸이 모자라면 막는다" 1 "숫자가 아닌 칸" \
    -- "$(rows short.txt "1 1000 1.0" "2 2000 1.5 30.0" "4 4000 2.1 55.0" "8 5000 9.0 80.0")"
# 남는 칸은 숫자 검사에 안 걸린다 — 칸 수 검사만 잡는 자리다.
run_case "칸이 남아도 막는다" 1 "숫자가 아닌 칸" \
    -- "$(rows long.txt "1 1000 1.0 12.0 9" "2 2000 1.5 30.0 9" "4 4000 2.1 55.0 9" "8 5000 9.0 80.0 9")"

: > "$work/empty.txt"
run_case "표본이 비면 막는다" 1 "표본이 비었다" -- "$work/empty.txt"
run_case "표본 파일이 없으면 막는다" 1 "표본이 비었다" -- "$work/없는파일.txt"

[ "$selftest_failed" -eq 0 ] && echo "무릎 판정 자기검증 통과" || echo "무릎 판정 자기검증 실패"
exit "$selftest_failed"
