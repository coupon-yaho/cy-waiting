#!/usr/bin/env bash
# 죽은 주소 판정의 자기검증 (TS-9).
#
# **닿지 않은 회차를 통과로 적으면 이 게이트가 사라진다.** 죽은 주소가 목록에
# 안 들어왔거나 아무도 안 골랐으면 "유출 0" 은 그 주소와 무관한 값이다.
set -uo pipefail
cd "$(git rev-parse --show-toplevel)" || exit 1
. test/load/selftest-lib.sh

SELFTEST_JUDGE=$PWD/test/load/evaluate-dead-addr.sh

echo "죽은 주소 판정 자기검증"

#         보낸것  200   202  나머지 산대도착 노출% 배제 배제켬
run_case "배제를 끄고 다 200 이면 충족" 0 "회차 내내 후보" -- 7921 7921 0 0 7921 100 0 0
run_case "배제를 켜고 다 200 이면 충족" 0 "배제가 그 대를 뺀다" -- 7921 7921 0 0 7921 100 1 1
run_case "5xx 가 새면 미달" 1 "5xx 로 샌다" -- 7921 7900 0 21 7900 100 0 0
run_case "도착이 모자라면 미달" 1 "어디로 갔나" -- 7921 7921 0 0 7000 100 0 0

# **줄이 켜진 회차는 미달이 아니다.** 요청이 뒷단에 안 갔으므로 죽은 주소를
# 밟은 적이 없다 — 하네스 조건이 어긋난 것을 제품 결함으로 읽으면 안 된다.
run_case "줄로 가면 판정 불가" 2 "줄로 갔다" -- 7921 7000 921 0 7000 100 0 0

run_case "노출이 낮으면 판정 불가" 2 "만 후보였다" -- 7921 7921 0 0 7921 30 0 0
run_case "배제를 켰는데 안 오르면 판정 불가" 2 "간 요청이 없다" -- 7921 7921 0 0 7921 100 0 1
run_case "배제를 껐는데 오르면 판정 불가" 2 "설정이 안 섰다" -- 7921 7921 0 0 7921 100 1 0
run_case "보낸 것이 적으면 판정 불가" 2 "최소" -- 100 100 0 0 100 100 0 0
run_case "합이 보낸 것보다 크면 판정 불가" 2 "합이" -- 7921 7000 900 900 7000 100 0 0
run_case "숫자가 아니면 판정 불가" 2 "정수여야" -- 7921 일곱 0 0 7921 100 0 0
run_case "인자 수가 다르면 판정 불가" 2 "여덟" -- 7921 7921 0 0 7921 100 0

exit "$selftest_failed"
