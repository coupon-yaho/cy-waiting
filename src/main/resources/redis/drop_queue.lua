-- 매진된 쿠폰의 줄을 지운다 (7.3 · 5.3.1).
--
-- KEYS[1]  queue:{cid}
-- KEYS[2]  alive:{cid}
-- KEYS[3]  stock:{cid}
-- KEYS[4]  dropfence:{cid}
-- ARGV[1]  판 번호. 리더가 리스를 새로 잡을 때 받은 값
--
-- 반환  1 이면 지웠다, 0 이면 안 지웠다
--
-- **이 저장소에서 되돌릴 수 없는 유일한 쓰기다.** 지운 줄을 되살리는 코드가
-- 없다 — `coupons:active` 는 발급 계층 소유라 여기서 다시 넣지 못한다. 그래서
-- 판단이 아니라 **쓰기 직전의 사실**로 한 번 더 막는다.
--
-- **지우는 것을 줄과 생존 신호로 좁힌다.** 임계를 지우면 임계가 뒤로 가 이미
-- 입장한 사람이 두 번째 토큰을 받고, 바닥값을 지우면 승격된 복제본에서 새
-- score 가 앞으로 가 줄 선 사람이 통째로 추월당한다. 유예에는 입장 표시가
-- 있어 차례가 왔던 사람이 종료를 안 받게 막는다.

-- **여기서 슬롯을 검사하지 않는다.** 클러스터는 KEYS 의 슬롯을 본문보다 먼저
-- 계산해 갈리면 CROSSSLOT 으로 거절하므로 그 코드는 클러스터에서 영영 안 돈다.
-- 단독 배치는 슬롯 개념이 없어 갈려도 문제가 없는데, 거기서만 정리가 멎는다.
-- 부르는 쪽이 샤드 수로 막는다.

-- **옛 리더의 명령은 안 듣는다** (CY-766). 지역 검사는 울타리가 아니다 —
-- 검사와 삭제 사이에 리스가 끝나면 옛 리더가 새 리더의 줄을 지운다. 리더 키는
-- 줄과 다른 슬롯이라 여기서 같이 못 읽으므로, 줄과 같은 슬롯에 마지막으로 지운
-- 판 번호를 남기고 그것보다 옛 판이면 거절한다.
--
-- **같은 판의 재시도는 막지 않는다.** 막으면 실패한 삭제가 영영 안 된다.
-- **0 은 리더가 아니라는 뜻이다.** 강등된 노드가 그 값을 들고 나오므로 여기서
-- 거절해야 한다. 안 막으면 울타리 표가 아직 없는 쿠폰이 그대로 지워진다.
local fence = tonumber(ARGV[1])
if fence == nil or fence ~= fence or fence ~= math.floor(fence) then
    return redis.error_reply('판 번호는 정수여야 한다: ' .. tostring(ARGV[1]))
end
if fence <= 0 then
    return 0
end
local seen = tonumber(redis.call('GET', KEYS[4]))
if seen ~= nil and seen == seen and fence < seen then
    return 0
end

local raw = redis.call('GET', KEYS[3])
-- **못 읽으면 안 지운다.** 못 읽은 것은 매진이 아니다 (CY-702). 여기서 지우면
-- 재고 키를 잃은 쿠폰의 줄이 통째로 사라지고 되살릴 방법이 없다.
if raw == false then
    return 0
end
-- **담는 쪽과 같은 모양만 읽는다.** 재고를 스냅샷에 담는 쪽은 정수 파싱이라
-- 지수 표기(`-1e20`)나 소수를 못 읽고 미상으로 넘긴다. 여기서 `tonumber` 로
-- 관대하게 읽으면, 수집이 미상이라 부른 값으로 삭제가 매진이라 판단해 그 줄을
-- 영영 지운다 — 두 판단이 갈리는 자리가 하필 되돌릴 수 없는 쓰기다.
--
-- **반대로 좁아도 안 된다.** 담는 쪽이 읽는 모양(앞의 `+` 를 포함해)을 여기서
-- 못 읽으면 그 쿠폰이 매진으로 보이면서 영영 안 지워지고, 죽은 줄이 폴링
-- 예산을 계속 먹는다. 두 쪽이 정확히 같은 모양이라야 한다.
local digits = string.match(raw, '^%s*[-+]?(%d+)%s*$')
-- **자릿수도 본다.** 담는 쪽은 64비트 정수라 범위를 넘으면 던져서 미상으로
-- 넘기는데, 여기서 `tonumber` 는 실수로 읽어 버린다. 열아홉 자리까지만 받으면
-- 두 쪽의 답이 갈리지 않는다 — 갈리는 자리가 하필 되돌릴 수 없는 쓰기다.
if digits == nil or #digits > 19 then
    return 0
end
local stock = tonumber(raw)
-- **재입고됐으면 안 지운다.** 수집과 삭제 사이에 돌아온 재고는 메모리 안의
-- 취소가 다음 스냅샷을 기다리는 동안 이 쓰기를 못 막는다.
if stock > 0 then
    return 0
end

-- **표를 먼저 남긴다.** 지우고 나서 남기면 그 사이에 죽었을 때 옛 리더가
-- 같은 줄을 다시 지울 수 있다. 표만 남고 안 지워지는 쪽이 안전하다.
redis.call('SET', KEYS[4], fence)
redis.call('DEL', KEYS[1], KEYS[2])
return 1
