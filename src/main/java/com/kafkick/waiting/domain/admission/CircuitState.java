package com.kafkick.waiting.domain.admission;

/**
 * 뒷단 서킷의 상태. <b>판정의 입력이다</b> (F3).
 *
 * <p>서킷이 열려도 판정이 모르면 계속 통과를 내고, 서킷이 그것을 가로채
 * fallback 으로 보낸다 — 사용자는 순번 대신 503 을 받는다. 더 나쁜 것은
 * 반쯤 열린 순간이다. 시험 요청이 아니라 <b>그때 도착한 모든 트래픽</b>이
 * 약한 뒷단에 꽂혀 즉시 재포화하고, 회복이 지연되거나 영영 안 된다.
 */
// **라이브러리 타입을 안 들인다.** 도메인이 resilience4j 를 알면 그날부터
// 그 라이브러리에 묶인다. 상태 셋만 받는다.
public enum CircuitState {

    /** 정상. 판정이 서킷을 안 본 것과 같다. */
    CLOSED,

    /** 열렸다. 뒷단이 못 받는다는 가장 직접적인 증거다 — 신규 유입은 줄로 간다. */
    OPEN,

    /** 반쯤 열렸다. 회복 판정이 공정하려면 <b>소량만</b> 닿아야 한다. */
    HALF_OPEN
}
