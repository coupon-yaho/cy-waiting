-- 판정 재료와 <b>그것을 잰 시각</b>을 한 번에 읽는다.
--
-- KEYS[1]  gw:snapshot   리더가 발행한 판정 재료
-- ARGV     없다. 시각을 밖에서 주면 이 스크립트를 둔 이유가 사라진다
--
-- 반환  {now, field1, value1, field2, value2, ...}
--   now  이 노드가 아니라 **레디스의** 지금 시각(초)
--
-- **나이를 두 벽시계의 차로 재지 않는다.** 발행 시각은 리더가 찍고 나이는 각
-- 노드가 재므로, 시계가 어긋나면 같은 스냅샷이 노드마다 다르게 낡는다. 그 차가
-- 한계를 넘으면 어떤 노드는 fail-open 으로 열리고 어떤 노드는 안 열린다.
--
-- 여기서 받은 시각으로 노드가 **자기 시계와의 차이를 배운다.** 그 보정은 요청
-- 경로 밖에서 일어나므로 불변식 1 을 안 건드린다.

-- **데이터를 먼저 읽는다.** TIME 을 앞에 두면 HGETALL 이 도는 사이 초 경계를
-- 넘을 수 있고, 그러면 나이가 최대 1 초 어리게 나온다.
local entries = redis.call('HGETALL', KEYS[1])
local now = redis.call('TIME')[1]
table.insert(entries, 1, now)
return entries
