#!/usr/bin/env bash
# 롤링 배포 판정의 자기검증 (TS-9).
#
# **이 판정이 "찬 인스턴스로 안 몰린다" 게이트를 열고 닫는다.** 헐거우면
# 램프가 아예 없어도 초록이 뜨고, 그 초록을 근거로 램프를 지우게 된다.
set -uo pipefail
cd "$(git rev-parse --show-toplevel)" || exit 1
. test/load/selftest-lib.sh

SELFTEST_JUDGE=$PWD/test/load/evaluate-rollout.sh
work=$(mktemp -d) || exit 1
trap 'rm -rf "$work"' EXIT

unset EARLY_SEC EARLY_MAX_RATIO LATE_SEC LATE_MIN_RATIO MIN_PER_SEC

check() {
    local name=$1 want_rc=$2 want_word=$3 steady=$4 rows=$5
    printf '%s\n' "$rows" > "$work/s.txt"
    EARLY_SEC="${EARLY_:-5}" EARLY_MAX_RATIO="${RATIO_:-70}" \
        LATE_SEC="${LATE_:-15}" LATE_MIN_RATIO="${LATERATIO_:-70}" \
        MIN_PER_SEC="${MINPS_:-10}" \
        run_case "$name" "$want_rc" "$want_word" -- "$work/s.txt" "$steady"
}

# 설정을 안 덮어쓰고 부른다. **하네스는 아무것도 안 넘긴다** — 그러니 실제
# 게이트를 가르는 것은 판정기의 기본값인데, 위 `check` 는 그 값을 매번 덮어써서
# 기본값을 한 번도 안 태운다. 기본 한계를 200 으로 바꿔도 다 통과한다.
bare() {
    local name=$1 want_rc=$2 want_word=$3 steady=$4 rows=$5
    printf '%s\n' "$rows" > "$work/s.txt"
    run_case "$name" "$want_rc" "$want_word" -- "$work/s.txt" "$steady"
}

# 램프가 다 오른 구간. 판정이 회복까지 보므로 통과해야 하는 사례에는 이것이
# 붙는다. 붙이지 않으면 "올라오는지를 못 본다" 로 끊긴다.
late='15 33 100
16 34 100
17 32 100'

echo "롤링 배포 판정 자기검증"

# 평상시 몫 33%. 램프가 있으면 처음 몇 초는 그보다 한참 낮다.
check "처음에 덜 받고 나중에 올라오면 충족" 0 "충족" 33 "0 5 100
1 9 100
2 14 100
3 20 100
4 26 100
5 33 100
$late"

# **램프가 없으면 처음부터 제 몫을 받는다.** 이 갈래가 안 물면 램프를 지워도
# 초록이 뜬다 — 이 판정이 지키려는 것이 정확히 그것이다.
check "처음부터 제 몫이면 미달" 1 "미달" 33 "0 33 100
1 34 100
2 33 100
3 32 100
4 33 100"

# **"결국 제 몫을 받는다" 로는 판정이 안 된다.** 위 미달 사례도 그건 참이다.
check "나중에 맞는 것으로는 못 덮는다" 1 "미달" 33 "0 30 100
1 31 100
2 33 100
3 33 100
4 33 100"

# 보고 시작 전(음수 초)은 안 센다. 그때는 새 인스턴스가 아예 없다.
check "보고 전 표본은 안 센다" 0 "충족" 33 "-2 0 100
-1 0 100
0 5 100
1 8 100
2 12 100
3 18 100
4 24 100
$late"

# **끝까지 굶어도 지금까지는 충족이었다.** 처음에 덜 받는지만 보면, 새
# 인스턴스가 영영 0% 인 것이 가장 잘 지킨 모습으로 읽힌다 — 램프가 아니라
# 배제다. 롤링 배포마다 새 인스턴스가 무기한 노는 회귀가 이 모양이다.
check "끝까지 굶으면 미달" 1 "램프가 아니라 배제" 33 "0 0 100
1 0 100
2 0 100
3 0 100
4 0 100
15 0 100
16 0 100
17 0 100"

# 올라오다 도로 주저앉는 것도 같은 갈래다. 첫 구간만 보면 구별이 안 된다.
check "올라오다 주저앉으면 미달" 1 "램프가 아니라 배제" 33 "0 5 100
1 12 100
2 20 100
3 26 100
4 30 100
15 8 100
16 7 100
17 9 100"

# **회복 구간이 없으면 넘어가지 않는다.** 넘어가면 올라오는지를 한 번도 안
# 본 실행이 충족으로 적힌다.
check "회복 구간이 없으면 판정 불가" 2 "올라오는지를 못 본다" 33 "0 5 100
1 9 100
2 14 100
3 20 100
4 26 100"

check "부하가 안 흐르면 판정 불가" 2 "판정 불가" 33 "0 1 3
1 0 2"
check "평상시 몫이 0 이면 막는다" 2 "견줄 것이 없다" 0 "0 5 100"
check "평상시 몫이 숫자가 아니면 막는다" 2 "정수여야" oops "0 5 100"
RATIO_=oops check "한계 비율이 숫자가 아니면 막는다" 2 "정수여야" 33 "0 5 100"

# 기본값이 게이트를 가르는 자리 둘. 여기가 없으면 기본 한계·기본 하한을
# 바꿔도 위 사례가 전부 통과한다.
bare "기본 한계는 평상시의 70% 다" 1 "처음부터 제 몫" 33 "0 24 100
1 24 100
2 24 100
3 24 100
4 24 100
$late"
bare "기본 하한도 평상시의 70% 다" 1 "램프가 아니라 배제" 33 "0 5 100
1 9 100
2 14 100
3 20 100
4 22 100
15 22 100
16 22 100
17 22 100"

out=$("$SELFTEST_JUDGE" "$work/없는파일" 33 2>&1); rc=$?
if [ "$rc" -eq 2 ] && printf '%s' "$out" | grep -q "표본 파일이 없다"; then
    echo "  ✓ 표본 파일이 없으면 막는다"
else
    echo "  ✗ 표본 파일이 없으면 막는다"
    selftest_failed=1
fi

exit $selftest_failed
