-- 뒷단 가용량 보고와 기준 시각을 **한 번에** 읽는다.
--
-- KEYS[1]  capacity:coupon-svc:v1   뒷단 인스턴스의 자기보고 해시
-- ARGV     없다. 기준 시각을 밖에서 주면 이 스크립트를 둔 이유가 사라진다
--
-- 반환  {now, field1, value1, field2, value2, ...}
--   now  이 노드의 지금 시각(초)
--
-- **한 명령으로 묶는 이유가 둘이다.**
--
-- 클러스터에서 키 없는 TIME 은 아무 노드로 간다. 보고는 이 키의 슬롯 주인에게
-- 가므로 둘이 다른 물리 노드의 벽시계가 되고, 그 차가 신선도 판정에 그대로
-- 실린다. 차가 창을 넘으면 보고가 전부 걸러져 크레딧이 하한에 박힌다.
--
-- 따로 내면 같은 순간이 아니다. 두 왕복 사이에 뒷단이 보고를 갱신하면 시계가
-- 완벽해도 나이가 음수로 나온다 — 그 경합을 덮으려고 판정을 느슨하게 하면
-- 죽은 인스턴스가 그만큼 오래 세어진다.

-- **데이터를 먼저 읽는다.** TIME 을 앞에 두면 HGETALL 이 도는 사이 초 경계를
-- 넘을 수 있고, 그러면 나이가 최대 1 초 어리게 나온다.
local entries = redis.call('HGETALL', KEYS[1])
local now = redis.call('TIME')[1]
table.insert(entries, 1, now)
return entries
