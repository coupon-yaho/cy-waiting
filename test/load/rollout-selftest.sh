#!/usr/bin/env bash
# 롤링 배포 판정의 자기검증 (TS-9).
#
# **이 판정이 "찬 인스턴스로 안 몰린다" 게이트를 열고 닫는다.** 헐거우면
# 램프가 아예 없어도 초록이 뜨고, 그 초록을 근거로 램프를 지우게 된다.
set -uo pipefail
cd "$(git rev-parse --show-toplevel)" || exit 1
. test/load/selftest-lib.sh

SELFTEST_JUDGE=$PWD/test/load/evaluate-rollout.sh
work=$(mktemp -d) || exit 1
trap 'rm -rf "$work"' EXIT

unset EARLY_SEC EARLY_MAX_RATIO LATE_SEC LATE_RISE_POINTS MIN_PER_SEC

check() {
    local name=$1 want_rc=$2 want_word=$3 steady=$4 rows=$5
    printf '%s\n' "$rows" > "$work/s.txt"
    EARLY_SEC="${EARLY_:-5}" EARLY_MAX_RATIO="${RATIO_:-70}" \
        LATE_SEC="${LATE_:-15}" LATE_RISE_POINTS="${RISE_:-5}" \
        MIN_PER_SEC="${MINPS_:-10}" \
        run_case "$name" "$want_rc" "$want_word" -- "$work/s.txt" "$steady"
}

# 설정을 안 덮어쓰고 부른다. **하네스는 아무것도 안 넘긴다** — 그러니 실제
# 게이트를 가르는 것은 판정기의 기본값인데, 위 `check` 는 그 값을 매번 덮어써서
# 기본값을 한 번도 안 태운다. 기본 한계를 200 으로 바꿔도 다 통과한다.
bare() {
    local name=$1 want_rc=$2 want_word=$3 steady=$4 rows=$5
    printf '%s\n' "$rows" > "$work/s.txt"
    run_case "$name" "$want_rc" "$want_word" -- "$work/s.txt" "$steady"
}

