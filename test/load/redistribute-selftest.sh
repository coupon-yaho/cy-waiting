#!/usr/bin/env bash
# 재분배 판정의 자기검증 (TS-9).
#
# **이 판정이 "열화 시 5초 내 재분배" 게이트를 열고 닫는다.** 헐거우면 유입이
# 영영 안 줄어도 초록이 뜨고, 엄하면 제때 줄었는데도 미달로 적힌다.
set -uo pipefail
cd "$(git rev-parse --show-toplevel)" || exit 1
. test/load/selftest-lib.sh

SELFTEST_JUDGE=$PWD/test/load/evaluate-redistribute.sh
work=$(mktemp -d) || exit 1
trap 'rm -rf "$work"' EXIT

# 물려받은 값을 버린다. 판정이 무는지를 보는 자리에서 그 입력이 흔들리면
# 무엇을 본 것인지 알 수 없다.
unset SLACK SUSTAIN BUDGET_SEC MIN_PER_SEC

check() {
    local name=$1 want_rc=$2 want_word=$3 target=$4 rows=$5
    printf '%s\n' "$rows" > "$work/s.txt"
    SLACK="${SLACK_:-8}" SUSTAIN="${SUSTAIN_:-3}" BUDGET_SEC="${BUDGET_:-5}" \
        MIN_PER_SEC="${MINPS_:-10}" \
        run_case "$name" "$want_rc" "$want_word" -- "$work/s.txt" "$target"
}

echo "재분배 판정 자기검증"

# 여유 200/40/120 에서 큰 대를 20 으로 낮추면 그 대의 몫은 200/360 → 20/180,
# 즉 55% 에서 11% 가 된다. 목표는 11 이다.
before='-2 55 100
-1 56 100'

# 2초 만에 목표에 닿아 머문다.
check "예산 안에 닿으면 충족" 0 "충족" 11 "$before
0 40 100
1 20 100
2 11 100
3 10 100
4 12 100"

# 6초에야 닿는다 — 예산 밖이다.
check "예산을 넘으면 미달" 1 "예산" 11 "$before
0 55 100
1 54 100
2 53 100
3 50 100
4 45 100
5 30 100
6 11 100
7 10 100
8 11 100"

# **줄기만 하고 목표엔 안 닿는다.** "줄었다" 로 판정하면 이것이 통과한다.
check "줄기만 하면 미달" 1 "닿은 적이 없다" 11 "$before
0 50 100
1 45 100
2 40 100
3 38 100
4 37 100
5 37 100"

# 흔들림이 목표를 한 번 스친다. 유지 조건이 없으면 이것이 회복으로 적힌다.
SUSTAIN_=3 check "스치기만 하면 미달" 1 "닿은 적이 없다" 11 "$before
0 55 100
1 11 100
2 50 100
3 52 100
4 51 100"

# **연속의 첫 초를 적는다.** 마지막 초를 쓰면 유지 조건 길이만큼 늘 늦게 적혀,
# 제때 줄었는데도 예산을 넘긴 것으로 나온다.
check "닿은 시각은 연속의 첫 초" 0 "재분배까지 3초" 11 "$before
0 55 100
1 40 100
2 20 100
3 11 100
4 10 100
5 12 100"

# 부하가 안 흐른 초는 비율을 못 믿는다. 그런 초만 있으면 판정 불가다.
check "부하가 안 흐르면 판정 불가" 2 "판정 불가" 11 "-1 5 5
0 1 3
1 0 2"

# 열화 전에 이미 목표에 있어도 그것으로 통과시키지 않는다. 0 초부터 본다.
check "열화 전 표본은 안 센다" 1 "닿은 적이 없다" 55 "-3 55 100
-2 55 100
-1 55 100
0 11 100
1 10 100
2 11 100"

# 설정이 숫자가 아니면 정수 비교가 오류를 내고 그대로 흘러 마지막 줄이 찍힌다.
SLACK_=oops check "허용폭이 숫자가 아니면 막는다" 2 "정수여야" 11 "0 11 100"
check "목표가 숫자가 아니면 막는다" 2 "정수여야" oops "0 11 100"

# **되돌아오는 방향도 같은 판정으로 본다.** 목표가 55 로 바뀔 뿐이다.
# 여기가 안 물면 열화만 보고 회복은 안 본 채로 게이트를 닫게 된다.
check "회복도 예산 안이면 충족" 0 "충족" 55 "-2 11 100
-1 11 100
0 30 100
1 55 100
2 54 100
3 56 100"
check "회복이 안 되면 미달" 1 "닿은 적이 없다" 55 "-2 11 100
-1 11 100
0 12 100
1 13 100
2 12 100
3 14 100"

out=$("$SELFTEST_JUDGE" "$work/없는파일" 11 2>&1)
if [ $? -eq 2 ] && printf '%s' "$out" | grep -q "표본 파일이 없다"; then
    echo "  ✓ 표본 파일이 없으면 막는다"
else
    echo "  ✗ 표본 파일이 없으면 막는다"
    selftest_failed=1
fi

exit $selftest_failed
